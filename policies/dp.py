"""
Diffusion Policy (DP; Chi et al., 2023), state-based, with the published configuration: the
conditional 1-D U-Net, a DDPM with 100 timesteps and the squared-cosine schedule, epsilon
prediction, AdamW with a cosine learning-rate schedule, and the EMA of the weights.

At deployment, an action chunk is generated by 100 steps of ancestral DDPM sampling from
Gaussian noise. As a triangular map, DP is an instance of the formulation with the Gaussian
reference N(0, I).
"""
import math

import torch
import torch.nn as nn

from .unet import ConditionalUnet1D, PowerEMA
from .common import StateNoise


def cosine_with_warmup(optimizer, warmup_steps, total_steps):
    """Linear warm-up followed by a cosine decay to zero (diffusers' 'cosine' schedule)."""
    def factor(step):
        """Learning-rate factor at step: linear warmup, then cosine decay to zero."""
        if step < warmup_steps:
            return step / max(1, warmup_steps)
        progress = (step - warmup_steps) / max(1, total_steps - warmup_steps)
        return max(0.0, 0.5 * (1.0 + math.cos(math.pi * progress)))
    return torch.optim.lr_scheduler.LambdaLR(optimizer, factor)


class DP(nn.Module):
    """
    Configuration keys: act_dim, step_embed_dim, down_dims, kernel_size, n_groups,
    n_train_timesteps, n_inference_steps, lr, betas, weight_decay, warmup_steps, batch_size,
    iterations, state_noise, state_noise_dims.
    """
    reference = 'gaussian'

    def __init__(self, cfg, dim_s, dim_a):
        super().__init__()
        self.cfg, self.act_dim = cfg, cfg['act_dim']
        self.h_p = dim_a // self.act_dim
        self.net = ConditionalUnet1D(self.act_dim, dim_s, cfg['step_embed_dim'], cfg['down_dims'],
                                     cfg['kernel_size'], cfg['n_groups'])

    def scheduler(self):
        """DDPM noise scheduler of the policy (diffusers)."""
        from diffusers.schedulers.scheduling_ddpm import DDPMScheduler
        return DDPMScheduler(num_train_timesteps=self.cfg['n_train_timesteps'], beta_start=1e-4, beta_end=2e-2,
                             beta_schedule='squaredcos_cap_v2', variance_type='fixed_small',
                             clip_sample=True, prediction_type='epsilon')

    def fit(self, S, A, log=print):
        """Train the noise-prediction network on the pairs (S, A)."""
        c = self.cfg
        A = A.reshape(A.shape[0], self.h_p, self.act_dim)
        sched = self.scheduler()
        ema = PowerEMA(self.net)
        opt = torch.optim.AdamW(self.net.parameters(), lr=c['lr'], betas=tuple(c['betas']), eps=1e-8,
                                weight_decay=c['weight_decay'])
        lr_sched = cosine_with_warmup(opt, c['warmup_steps'], c['iterations'])
        noise = StateNoise(c.get('state_noise', 0.0), c.get('state_noise_dims'), S.shape[1], S.device)
        bs, n_it = min(c['batch_size'], A.shape[0]), c['iterations']
        self.net.train()
        for i in range(n_it):
            idx = torch.randint(0, A.shape[0], (bs,), device=A.device)
            a, s = A[idx], noise(S[idx])
            zeta = torch.randn_like(a)
            t = torch.randint(0, c['n_train_timesteps'], (bs,), device=A.device).long()
            loss = nn.functional.mse_loss(self.net(sched.add_noise(a, zeta, t), t, s), zeta)
            opt.zero_grad()
            loss.backward()
            opt.step()
            lr_sched.step()
            ema.step(self.net)
            if (i + 1) % max(1, n_it // 10) == 0:
                log('  iteration %d/%d  loss %.4f' % (i + 1, n_it, loss.item()))
        self.net.load_state_dict(ema.averaged_model.state_dict())      # deploy the averaged network
        self.eval()

    @torch.no_grad()
    def sample(self, s, z=None):
        """Action chunks at states s (n, dim_s), by DDPM sampling from Gaussian noise (z is not used)."""
        sched = self.scheduler()
        sched.set_timesteps(self.cfg['n_inference_steps'])
        x = torch.randn((s.shape[0], self.h_p, self.act_dim), device=s.device)
        for t in sched.timesteps:
            x = sched.step(self.net(x, t, s), t, x).prev_sample
        return x.reshape(s.shape[0], -1)
